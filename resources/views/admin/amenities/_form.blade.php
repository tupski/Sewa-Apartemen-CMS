<script>
    (function () {
        var hidden  = document.getElementById('icon');
        var preview = document.getElementById('icon-preview');
        var custom  = document.getElementById('icon-custom');
        var search  = document.getElementById('icon-search');
        var noResults = document.getElementById('icon-no-results');

        function setIcon(iconClass) {
            // Normalise: strip "fa-solid " prefix if the user typed it
            var cls = iconClass.replace(/^fa-solid\s+/, '').trim();
            hidden.value  = cls ? 'fa-solid ' + cls : '';
            preview.innerHTML = cls ? '<i class="fa-solid ' + cls + '"></i>' : '';
            custom.value  = cls;

            // Highlight selected button, clear others
            document.querySelectorAll('.icon-pick').forEach(function (btn) {
                var active = btn.dataset.icon === cls;
                btn.classList.toggle('border-blue-500', active);
                btn.classList.toggle('bg-blue-50',      active);
                btn.classList.toggle('text-blue-600',   active);
                btn.classList.toggle('border-gray-200', !active);
                btn.classList.toggle('bg-white',        !active);
                btn.classList.toggle('text-gray-600',   !active);
            });
        }

        // Click handlers for picker buttons
        document.querySelectorAll('.icon-pick').forEach(function (btn) {
            btn.addEventListener('click', function () { setIcon(btn.dataset.icon); });
        });

        // Manual input
        custom.addEventListener('input', function () {
            setIcon(custom.value.trim());
        });

        // Search / filter
        search.addEventListener('input', function () {
            var q = this.value.toLowerCase().trim();
            var visibleApartment = 0;
            var visibleOther     = 0;

            document.querySelectorAll('#grid-apartment .icon-pick').forEach(function (btn) {
                var match = !q
                    || btn.dataset.icon.toLowerCase().includes(q)
                    || btn.dataset.label.toLowerCase().includes(q);
                btn.style.display = match ? '' : 'none';
                if (match) visibleApartment++;
            });

            document.querySelectorAll('#grid-other .icon-pick').forEach(function (btn) {
                var match = !q
                    || btn.dataset.icon.toLowerCase().includes(q)
                    || btn.dataset.label.toLowerCase().includes(q);
                btn.style.display = match ? '' : 'none';
                if (match) visibleOther++;
            });

            // Toggle group labels based on visibility
            document.querySelector('[data-group="apartment"]').style.display =
                visibleApartment ? '' : 'none';
            document.querySelector('[data-group="other"]').style.display =
                visibleOther ? '' : 'none';

            noResults.classList.toggle('hidden', visibleApartment + visibleOther > 0);
        });

        // Initialise with saved value (strip "fa-solid " prefix for the setter)
        var saved = (hidden.value || '').replace(/^fa-solid\s+/, '').trim();
        setIcon(saved || 'fa-wifi');
    })();

    // Auto-generate slug from name
    document.getElementById('name').addEventListener('input', function () {
        var slugField = document.getElementById('slug');
        if (!slugField.dataset.touched) {
            slugField.value = this.value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
        }
    });
    document.getElementById('slug').addEventListener('input', function () {
        this.dataset.touched = '1';
    });
</script>
